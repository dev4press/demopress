<?php

use Dev4Press\v56\Core\Quick\KSES;
use Dev4Press\v56\Core\Quick\Sanitize;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

?>
<div class="d4p-content">

	<?php

	if ( isset( $_GET['results'] ) ) {
		$results = is_string( $_GET['results'] ) ? json_decode( wp_unslash( $_GET['results'] ) ) : null;

		?>

        <div class="d4p-group d4p-group-information">
            <h3><?php esc_html_e( "Cleanup Results", "demopress" ); ?></h3>
            <div class="d4p-group-inner">
				<?php

				$list = array();

				if ( is_object( $results ) ) {
					foreach ( $results as $gen => $data ) {
						if ( ! is_array( $data ) && ! is_object( $data ) ) {
							continue;
						}

						$gen_label = demopress()->get_generator_label( $gen );

						foreach ( $data as $type => $value ) {
							if ( ! is_int( $value ) || $value < 0 ) {
								continue;
							}

							$type_label = str_replace( '::', ' / ', Sanitize::text( $type, false, false ) );
							$list[] = '<strong>' . esc_html( $gen_label ) . '</strong>: ' . sprintf(
								esc_html__( "Removed %s items for %s.", "demopress" ),
								'<strong>' . $value . '</strong>',
								'<strong>' . esc_html( $type_label ) . '</strong>'
							);
						}
					}
				}

				if ( ! empty( $list ) ) {
					echo wp_kses( implode( '<br/>', $list ), array( 'strong' => array(), 'br' => array() ) );
				} else {
					esc_html_e( "Results are not valid.", "demopress" );
				}

				?>
            </div>
        </div>

		<?php

	} else {

		?>


        <div class="d4p-group d4p-group-information">
            <h3><?php esc_html_e( "Important Information", "demopress" ); ?></h3>
            <div class="d4p-group-inner">
				<?php esc_html_e( "This tool can remove data generated by the plugin. Any other data created by the user will not be affected. If the data is generated by the plugin, and later edited by user, it will still be eligible for deletion!", "demopress" ); ?>
                <br/><br/>
				<?php esc_html_e( "This tool deletes data directly in the database. After the deletion, it is possible that additional orphaned draft records remain in the database.", "demopress" ); ?>
				<?php esc_html_e( "Deletion operations are not reversible, and it is highly recommended to create database backup before proceeding with this tool.", "demopress" ); ?>
            </div>
        </div>

		<?php

		foreach ( demopress()->generators as $code => $generator ) {
			$obj    = demopress()->get_generator( $code );
			$notice = $obj->get_cleanup_notice();
			$types  = $obj->get_cleanup_types();
			$field  = 'demopresstools[cleanup][' . $obj->name . ']';

			?>

            <div class="d4p-group d4p-group-tools demopress-group-cleanup">
                <h3>
                    <i style="float: left; margin-right: 10px;" aria-hidden="true" class="<?php echo esc_attr( $generator['settings']['icon'] ); ?> d4p-icon-fw"></i><?php echo esc_html( $generator['label'] ); ?>
                </h3>
                <div class="d4p-group-inner">
					<?php foreach ( (array) $notice as $message ) { ?>
                        <p><?php echo wp_kses( $message, KSES::allowed_html_standard() ); ?></p>
					<?php } ?>

					<?php

					foreach ( $types as $name => $label ) {
						$count = absint( $obj->get_cleanup_count( $name ) );

						?>

                        <label>
                            <input type="checkbox" class="widefat" name="<?php echo esc_attr( $field . '[' . $name . ']' ); ?>" value="on"<?php disabled( $count, 0 ); ?>/>
                            <?php echo esc_html( $label ); ?> (<?php printf( esc_html( _n( "%s item", "%s items", $count, "demopress" ) ), '<strong>' . $count . '</strong>' ); ?>)
                        </label>

						<?php

						if ( $obj->attached_images ) {
							$images = absint( $obj->get_attached_images_count( $name ) );

							if ( $images ) {

								?>

                                <label style="margin-left: 25px">
                                    <input type="checkbox" class="widefat" name="<?php echo esc_attr( $field . '[attached-images::' . $name . ']' ); ?>" value="on"/>
                                    <?php esc_html_e( "Attached Images", "demopress" ); ?> (<?php printf( esc_html( _n( "%s item", "%s items", $images, "demopress" ) ), '<strong>' . $images . '</strong>' ); ?>)
                                </label>

								<?php

							}
						}
					}

					?>
                </div>
            </div>

			<?php

		}
	}

	?>

</div>
